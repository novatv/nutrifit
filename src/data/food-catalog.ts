/**
 * Catálogo local de alimentos.
 *
 * Valores por 100 g de porción comestible, derivados de tablas de composición
 * (USDA FoodData Central y BEDCA). Son valores de REFERENCIA para un alimento
 * genérico: una pechuga concreta o una marca concreta pueden desviarse un
 * 10-15%. Sirven para estimar el día, no para una pauta clínica.
 *
 * Criterios:
 * - Carnes, pescados, verduras y frutas: en crudo, salvo que el nombre diga
 *   otra cosa ("cocido", "asado", "en conserva").
 * - Legumbres y cereales: se incluye la versión cocida cuando es la forma en
 *   que se come y se pesa en el plato.
 * - `fiberG`, `sugarG` y `sodiumMg` son ORIENTATIVOS y solo se rellenan cuando
 *   el dato es relevante para el alimento.
 * - `allergens` es un filtro DURO aguas abajo (ver `findSubstitutes`): ante la
 *   duda se marca el alérgeno, nunca se omite. La avena va marcada como gluten
 *   por contaminación cruzada habitual en el cereal comercial.
 * - `dietPatterns` se declara SIEMPRE: un alimento sin patrones solo se
 *   considera apto para dieta omnívora.
 */

import type { Allergen, DietPattern, Food, Nutrients } from '@/types/domain';

/* ------------------------------------------------------------------ tipos */

/**
 * Grupo dietético del alimento. Es una forma corta de declarar los cuatro
 * patrones sin repetirlos en cada fila.
 */
export type DietGroup = 'vegan' | 'vegetarian' | 'fish' | 'meat';

export const DIET_PATTERNS_BY_GROUP: Record<DietGroup, DietPattern[]> = {
  // Vegetal puro: vale para todas las dietas.
  vegan: ['omnivore', 'vegetarian', 'vegan', 'pescatarian'],
  // Lácteos y huevos: todas menos vegana.
  vegetarian: ['omnivore', 'vegetarian', 'pescatarian'],
  // Pescado y marisco: omnívora y pescetariana.
  fish: ['omnivore', 'pescatarian'],
  // Carne: solo omnívora.
  meat: ['omnivore'],
};

/* ---------------------------------------------------------------- helper */

/**
 * Construye una entrada del catálogo.
 *
 * @param id            Identificador estable; nunca se reutiliza ni se traduce.
 * @param name          Nombre mostrado (español).
 * @param servingLabel  Ración habitual en lenguaje natural ("1 filete").
 * @param servingGrams  Gramos de esa ración habitual.
 * @param per100g       Nutrientes por 100 g.
 * @param group         Grupo dietético (ver DIET_PATTERNS_BY_GROUP).
 * @param tags          Etiquetas para búsqueda, sustituciones y lista de compra.
 * @param allergens     Alérgenos declarados. Ante la duda, se marca.
 * @param barcode       Código de barras de ejemplo, solo en formatos envasados.
 */
function f(
  id: string,
  name: string,
  servingLabel: string,
  servingGrams: number,
  per100g: Nutrients,
  group: DietGroup,
  tags: string[],
  allergens: Allergen[] = [],
  barcode?: string,
): Food {
  return {
    id,
    name,
    servingLabel,
    servingGrams,
    per100g,
    source: 'usda',
    tags,
    allergens,
    dietPatterns: DIET_PATTERNS_BY_GROUP[group],
    ...(barcode ? { barcode } : {}),
  };
}

