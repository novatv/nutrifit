/**
 * Biblioteca de ejercicios.
 *
 * Datos puros: sin React, sin red, sin estado. Todas las cadenas visibles son
 * claves i18n; aquí no se escribe nunca texto para el usuario final.
 *
 * Convención de claves:
 *   nombre       -> `exercise.<slug_snake>`
 *   instrucción  -> `exercise.<slug_snake>.cue.<token>`
 *   error común  -> `exercise.<slug_snake>.mistake.<token>`
 *   nota segura  -> `exercise.<slug_snake>.safety.<token>`
 *
 * El campo `equipment` lista TODO el material necesario: un ejercicio solo se
 * puede hacer si el usuario dispone de todos esos elementos. `['none']`
 * significa que no hace falta nada (entreno en casa).
 */

import type {
  Difficulty,
  Equipment,
  Exercise,
  MovementPattern,
  MuscleGroup,
} from '@/types/domain';

const toSnake = (slug: string): string => slug.replace(/-/g, '_');

/**
 * Construye un ejercicio a partir de datos posicionales.
 * Orden: slug, patrón, músculos primarios, secundarios, equipo, dificultad,
 * instrucciones, errores comunes, notas de seguridad, alternativas.
 */
function s(
  slug: string,
  pattern: MovementPattern,
  primary: MuscleGroup[],
  secondary: MuscleGroup[],
  equipment: Equipment[],
  difficulty: Difficulty,
  cues: string[],
  mistakes: string[],
  safety: string[],
  alternatives: string[],
): Exercise {
  const base = `exercise.${toSnake(slug)}`;
  return {
    id: slug,
    slug,
    nameKey: base,
    pattern,
    primaryMuscles: primary,
    secondaryMuscles: secondary,
    equipment,
    difficulty,
    instructionKeys: cues.map((c) => `${base}.cue.${c}`),
    commonMistakeKeys: mistakes.map((m) => `${base}.mistake.${m}`),
    safetyNoteKeys: safety.map((n) => `${base}.safety.${n}`),
    alternatives,
  };
}

