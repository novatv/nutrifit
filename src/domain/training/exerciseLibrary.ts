const BY_SLUG: ReadonlyMap<string, Exercise> = new Map(EXERCISES.map((e) => [e.slug, e]));

/** Devuelve el ejercicio con ese slug, o `undefined` si no existe. */
export function getExercise(slug: string): Exercise | undefined {
  return BY_SLUG.get(slug);
}

/** Igual que `getExercise` pero lanza: úsalo solo con slugs de la propia biblioteca. */
export function getExerciseOrThrow(slug: string): Exercise {
  const found = BY_SLUG.get(slug);
  if (!found) throw new Error(`Ejercicio desconocido: ${slug}`);
  return found;
}

/** Todos los ejercicios de un patrón de movimiento, en el orden del catálogo. */
export function byPattern(pattern: MovementPattern): Exercise[] {
  return EXERCISES.filter((e) => e.pattern === pattern);
}

/** true si el equipo disponible cubre todo lo que pide el ejercicio. */
export function canPerform(exercise: Exercise, equipment: Equipment[]): boolean {
  const owned = new Set<Equipment>(equipment);
  return exercise.equipment.every((needed) => needed === 'none' || owned.has(needed));
}

/** Ejercicios realizables con el equipo disponible. `[]` o `['none']` = solo peso corporal. */
export function availableWith(equipment: Equipment[]): Exercise[] {
  return EXERCISES.filter((e) => canPerform(e, equipment));
}

/** Ejercicios que trabajan ese músculo como primario o secundario. */
export function byMuscle(muscle: MuscleGroup): Exercise[] {
  return EXERCISES.filter(
    (e) => e.primaryMuscles.includes(muscle) || e.secondaryMuscles.includes(muscle),
  );
}

